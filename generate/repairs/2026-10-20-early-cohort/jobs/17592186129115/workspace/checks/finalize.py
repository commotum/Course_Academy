"""Compare current records with delivery, and prepare normalized native cases."""
import collections
import hashlib
import itertools
import json
from pathlib import Path
import sys
sys.dont_write_bytecode = True
from validate import W, E, save, features, selected, bank, g
from regressions import check_record

comparisons = {}
native = []
for stage, filename in [('fresh', 'fresh-records.json'),
                        ('batch', 'batch-records.json'),
                        ('cf', 'counterfactual-records.json')]:
    raw = json.loads((E/filename).read_text())
    accepted = json.loads((E/('delivery-'+stage)/'accepted.json').read_text())
    for record in raw + accepted:
        check_record(record)
    before, after = features(raw), features(accepted)
    assert before == after, (stage, before, after)
    def visible_signature(record):
        from regressions import matrix
        return (tuple(map(tuple, matrix(record['question'][':question/problem']))),
                tuple(sorted((tuple(map(tuple, b)), i == selected(record))
                             for i, b in enumerate(bank(record)))))
    assert sorted(map(visible_signature, raw)) == sorted(map(visible_signature, accepted))
    # Check the saved sample really is generated by the current runtime.
    if stage == 'fresh':
        assert raw == [g.generate('moderate', i) for i in range(702311, 702343)]
    comparisons[stage] = {'before': before, 'after': after,
                          'coverage_and_shortcut_results_preserved': True}
    if stage != 'fresh':
        for n, record in enumerate(accepted):
            f = record['question'][':question/answer-fields'][0]
            native.append({'label': stage+str(n), 'record': record, 'checks': [
                {'field_index': 0, 'submitted_answer_id': a[':answer/id'],
                 'expected': 'accepted' if i == selected(record) else 'rejected',
                 'purpose': 'delivered operation independently tested against echelon conditions'}
                for i, a in enumerate(f[':answer-field/choices'])]})
save('delivered-grader-input.json', native)

# Finite structural witness for the changed sampler: every allowed correct
# operation has four same-size, same-no-op-count incorrect alternatives.
# Bit masks are independent of the runtime's list-matrix echelon predicate.
cells = list(range(16))
ops = [(n, sum(1 << i for i in c)) for n in (1, 2, 3)
       for c in itertools.combinations(cells, n)]
def echelon_bits(bits):
    last = -1
    zero = False
    for row in range(4):
        r = (bits >> (4 * row)) & 15
        if not r:
            zero = True
        else:
            p = (r & -r).bit_length() - 1
            if zero or p <= last:
                return False
            last = p
    return True

masks = {m for role in json.loads((W/'catalogue.json').read_text()) for m in role['masks']}
sizes = collections.Counter()
minimum_alternatives = 10000
correct_operations = 0
for mask in masks:
    assert not echelon_bits(mask)
    wrong = collections.Counter((n, (o & ~mask).bit_count()) for n, o in ops
                                if not echelon_bits(mask & ~o))
    good = [(n, o) for n, o in ops if echelon_bits(mask & ~o)]
    assert good
    for n, operation in good:
        available = wrong[n, (operation & ~mask).bit_count()]
        assert available >= 4, (mask, n, operation, available)
        minimum_alternatives = min(minimum_alternatives, available)
        sizes[n] += 1
        correct_operations += 1
save('sampler-support.json', {'zero_structures': len(masks),
    'eligible_correct_operations': correct_operations,
    'correct_operation_sizes': dict(sizes),
    'minimum_matched_distractors_available': minimum_alternatives,
    'failures': 0, 'method': 'Independent bit-row leading-column and bottom-zero witness over the finite catalogue.'})

