"""Finding a system's solution from its graph; local step-7 candidate.

math basis 1356 / lineage 01a12a15-3e0a-75a1-9dac-f8b8c5d5c3f1.
Two unrated practice sources share one two-blank graphical-intersection template
with standard/standard and standard/slope-intercept equation layouts. Missing
corrects are derived; the canonical example supplies the fixed solution prose.
All difficulty labels and finite sampling bounds are authored, not source labels.
See the adjacent evidence folder for exact raw sources, repairs and validation.
Plots are generated by the own-folder frozen Matplotlib renderer. No DB writes.
"""
from __future__ import annotations
import argparse
from functools import lru_cache
import hashlib
import json
import random
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path
import sympy as sp

KP_ID = 17592186138428
KP_UUID = '0f80bc47-7b56-5357-b4e7-718f4ddfa41b'
TITLE = 'Finding the Solution to a System From Its Graph'
VERSION = 'graph-system-6'
HERE = Path(__file__).resolve().with_suffix('')
SOURCE = {'database':'math','basis':1356,'lineage':'01a12a15-3e0a-75a1-9dac-f8b8c5d5c3f1'}
TEMPLATES = ('standard_standard', 'standard_slope')
LEVELS = ('easy','moderate','hard')
# Entire finite domains: no parallel/coincident systems, fractions to read, or algebra.
SLOPES = {'easy':('-1','-1/2','1/2','1','2'),
          'moderate':('-4','-3','-2','-1','1','2','3','4'), 'hard':('-2','-1','1','2')}
LIMITS = {'easy':4,'moderate':4,'hard':5}

def digest(value):
    return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':')).encode()).hexdigest()

def term(coefficient, variable):
    c = int(coefficient)
    return ('-' if c < 0 else '') + (str(abs(c)) if abs(c) != 1 else '') + variable

def sum_terms(a, b):
    return a + (' - ' + b[1:] if b.startswith('-') else ' + ' + b)

def row(m, x, y):
    """Primitive standard equation, x coefficient positive; no silent scaling slots."""
    n,d = int(m.p),int(m.q)
    a,b,c = n,-d,n*x-d*y
    if a < 0: a,b,c = -a,-b,-c
    return [a,b,c]

def equations(p, template):
    x,y = p['x'],p['y']
    rows = [row(sp.Rational(p[k]),x,y) for k in ('m1','m2')]
    texts = [sum_terms(term(a,'x'),term(b,'y'))+' = '+str(c) for a,b,c in rows]
    if template == 'standard_slope':
        m = sp.Rational(p['m2']); intercept = sp.Rational(y)-m*x
        # All slope-intercept rows use integral slopes in this layout.
        texts[1] = 'y ='+term(m,'x') + (' - '+str(-intercept) if intercept < 0 else ' + '+str(intercept))
    return rows,texts

def validate_parameters(level, template, parameters):
    if set(parameters) != {'x','y','m1','m2'}: raise ValueError('Parameters must be exactly x,y,m1,m2')
    p = dict(parameters)
    if any(type(p[k]) is not int for k in ('x','y')): raise ValueError('Coordinates must be integers')
    for k in ('m1','m2'):
        try: m = sp.Rational(p[k])
        except (TypeError,ValueError): raise ValueError('Invalid rational slope') from None
        p[k] = str(m)
        if p[k] not in SLOPES[level]: raise ValueError('Slope outside level domain')
    n = LIMITS[level]
    if level == 'easy':
        if not all(1 <= p[k] <= n for k in ('x','y')): raise ValueError('Easy uses first-quadrant coordinates 1..4')
        if sp.Rational(p['m1'])*sp.Rational(p['m2']) >= 0: raise ValueError('Easy uses opposing slopes')
    elif any(abs(p[k]) > n for k in ('x','y')): raise ValueError('Coordinate outside level bound')
    if level == 'moderate' and p['x'] > 0 and p['y'] > 0: raise ValueError('Moderate requires at least one signed or zero coordinate')
    if level == 'hard' and any(p[k] % 2 == 0 for k in ('x','y')): raise ValueError('Hard reads two odd coordinates between even-numbered ticks')
    if p['m1'] == p['m2']: raise ValueError('Lines must have a unique intersection')
    if template == 'standard_slope' and sp.Rational(p['m2']).q != 1: raise ValueError('Slope-intercept layout uses an integer slope')
    return p

@lru_cache(maxsize=6)
def domain(level, template):
    """Enumerate all valid finite peers at this level, independent of seed."""
    n=LIMITS[level]; coords=range(1,n+1) if level == 'easy' else range(-n,n+1)
    result=[]
    for x in coords:
        for y in coords:
            for m1 in SLOPES[level]:
                for m2 in SLOPES[level]:
                    p={'x':x,'y':y,'m1':m1,'m2':m2}
                    try: result.append(validate_parameters(level,template,p))
                    except ValueError: pass
    return result

def plot_data(p, rows, texts, template, level):
    # Fixed source-comparison windows at exact source geometry; other windows derive
    # from the intersection and axes. Both leave at least 3 units around the answer.
    if p == {'x':3,'y':-2,'m1':'-1','m2':'-2'} and template == 'standard_standard':
        bounds=[-3.5,7.5,-4.5,4.5]
    elif p == {'x':3,'y':0,'m1':'4','m2':'-3'} and template == 'standard_slope':
        bounds=[-2.5,7.5,-4.5,4.5]
    else:
        x,y=p['x'],p['y']; bounds=[min(-2.5,x-3.5),max(3.5,x+3.5),min(-2.5,y-3.5),max(3.5,y+3.5)]
    return {'intersection':[p['x'],p['y']], 'rows':rows,'labels':texts,'bounds':bounds,
            'colors':['#f4a300','#2275bb'],'unit_grid':True,'tick_increment':2 if level=='hard' else 1,'renderer_version':VERSION}

def render_plots(data, output_dir=None):
    """Own-folder Matplotlib; unique inputs and atomic PNG plus JSON writes.

    Cache is never pruned. Both PNG and sidecar are required for a cache hit.
    This helper takes already computed mathematical data and never samples.
    """
    out=Path(output_dir) if output_dir else HERE/'plots'
    out.mkdir(parents=True,exist_ok=True)
    key=digest(data)
    paths={role:str(out/(key+'-'+role+'.png')) for role in ('prompt','solution')}
    if not all(Path(v).is_file() and Path(v).with_suffix('.json').is_file() for v in paths.values()):
        with tempfile.NamedTemporaryFile(mode='w',suffix='.json',prefix='input-',dir=out,delete=False) as f:
            json.dump({'data':data,'paths':paths},f); input_path=Path(f.name)
        try:
            subprocess.run([sys.executable,str(HERE/'render.py'),str(input_path)],check=True,capture_output=True,text=True)
        finally: input_path.unlink(missing_ok=True)
    return paths

def generate(level, seed=0, template=None, field_type=None, parameters=None, profile=None):
    if level not in LEVELS: raise ValueError('Unknown difficulty')
    if field_type not in (None,'blank',':answer-field.type/blank'): raise ValueError('Only two blanks are supported')
    if profile not in (None,'observed_layout','authored'): raise ValueError('Unknown profile')
    rng=random.Random(seed); template=template or rng.choice(TEMPLATES)
    if template not in TEMPLATES: raise ValueError('Unknown template')
    p=validate_parameters(level,template,parameters) if parameters is not None else dict(rng.choice(domain(level,template)))
    rows,texts=equations(p,template)
    data=plot_data(p,rows,texts,template,level); assets=render_plots(data)
    # The brace and split dollar strings are repaired into the authoritative widget
    # layout: visible left brace, stacked rows, two separate blanks in one tuple.
    system='$$\n'+r'\left\{\begin{array}{l}'+texts[0]+r'\\'+texts[1]+r'\end{array}\right.'+'\n$$'
    prompt='![]('+assets['prompt']+')\n\nConsider the following system of equations:\n'+system+'\n\nUse the diagram provided to determine the solution $(x, y)$ of this system.\n\nThe solution is\n$($ {{field-1}} $,$ {{field-2}} $)$.'
    coordinate=f"({p['x']},{p['y']})"
    solution='The solution of the system corresponds to the point of intersection of the lines.\n\n![]('+assets['solution']+')\n\nIn this case, we have the point $'+coordinate+'$. Therefore, the solution to the given system is $'+coordinate+'$.'
    # A mathematical task is the unordered pair of primitive line equations, so
    # equivalent layouts and reversed line colors do not inflate unique-task counts.
    # Numbered-tick scale is assessed: hard intermediate coordinate reading differs
    # from directly numbered coordinate reading of the same mathematical lines.
    task=digest({'lines':sorted(rows),'major_tick_increment':data['tick_increment'],'minor_grid_increment':1})
    content=digest({'version':VERSION,'prompt':prompt,'solution':solution,'bank':[str(p['x']),str(p['y'])]})
    qid=uuid.uuid5(uuid.NAMESPACE_URL,KP_UUID+'/'+content)
    fields=[]
    for key,value in (('field-1',p['x']),('field-2',p['y'])):
        fid=uuid.uuid5(qid,key); aid=uuid.uuid5(fid,'math:'+str(value))
        fields.append({':answer-field/id':str(fid),':answer-field/key':key,':answer-field/type':':answer-field.type/blank',
                       ':answer-field/choices':[{':answer/id':str(aid),':answer/type':':answer.type/math',':answer/value':str(value)}],
                       ':answer-field/correct':[':answer/id',str(aid)]})
    return {'knowledge_point':{'db_id':KP_ID,'id':KP_UUID,'title':TITLE},
            'question':{':question/id':str(qid),':question/difficulty':':question.difficulty/'+level,':question/problem':prompt,
                        ':question/worked-solution':solution,':question/answer-fields':fields},
            'generation':{'version':VERSION,'seed':seed,'template':template,'parameters':p,'bank_profile':profile,
                          'source_analysis':SOURCE,'difficulty_origin':'authored; both captured sources unrated',
                          'answer_origin':'independently derived; source correct refs absent','solution_origin':'canonical e-13129 prose instantiated',
                          'parameter_fingerprint':task,'mathematical_fingerprint':task,'content_fingerprint':content,
                          'sympy_version':sp.__version__,'plot_rating':'heavy','plot_assets':assets,'plot_data':data,
                          'presentation_repairs':['system brace/stacked rows','balanced inline tuple dollars'],
                          'domain':{'coordinate_bound':LIMITS[level],'slopes':SLOPES[level],'unique_intersection':True}}}

# EASY — authored first-quadrant intersection reading, opposing familiar slopes.
def generate_easy(seed=0,template=None,field_type=None,parameters=None,profile=None):
    """Read two positive unit-grid coordinates 1..4; slopes oppose, |m|<=2."""
    return generate('easy',seed,template,field_type,parameters,profile)

# MODERATE — authored signed integer grid reading with numbered unit ticks.
def generate_moderate(seed=0,template=None,field_type=None,parameters=None,profile=None):
    """Read signed/zero numbered-unit coordinates -4..4; both source graphs are peers."""
    return generate('moderate',seed,template,field_type,parameters,profile)

# HARD — authored odd coordinates between even-numbered ticks, two entries.
def generate_hard(seed=0,template=None,field_type=None,parameters=None,profile=None):
    """Read two odd coordinates -5..5 between even-numbered major ticks. Familiar
    slopes have |m|=1 or 2; unit minor grid supplies exact intermediate positions.

    No algebra, approximate coordinates, nonlinear lines, or classification tasks.
    Both coordinates require reading one grid square between numbered ticks.
    This same-skill scale demand is authored, not a recovered source label.
    """
    return generate('hard',seed,template,field_type,parameters,profile)

def markdown(r):
    q=r['question']; fields=q[':question/answer-fields']
    return q[':question/problem']+'\n\nEntries: '+', '.join(f[':answer-field/choices'][0][':answer/value'] for f in fields)+'\n\n'+q[':question/worked-solution']

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--difficulty',choices=(*LEVELS,'all'),default='all'); parser.add_argument('--seed',type=int,default=0)
    parser.add_argument('--template',choices=TEMPLATES); parser.add_argument('--profile',choices=('observed_layout','authored'))
    parser.add_argument('--count',type=int,default=1); parser.add_argument('--format',choices=('markdown','json'),default='markdown')
    args=parser.parse_args()
    if args.count < 1: parser.error('Count must be positive')
    records=[generate(level,args.seed+i,args.template,profile=args.profile) for level in (LEVELS if args.difficulty=='all' else [args.difficulty]) for i in range(args.count)]
    print(json.dumps(records,indent=2) if args.format=='json' else '\n\n---\n\n'.join(markdown(r) for r in records))
if __name__=='__main__': main()
